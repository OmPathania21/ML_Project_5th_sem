"""Generates numbers.tex (LaTeX macros) from code/outputs/models/diabetes_summary.json, so every Unit 5 number in the
report comes straight from the notebook run.  Run:  python3 build_numbers.py"""
import json
from pathlib import Path

HERE = Path(__file__).parent
S = json.loads((HERE / "../../../../code/outputs/models/diabetes_summary.json").resolve().read_text().replace("NaN", "null"))

macros = {}
def m(name, value):
    macros[name] = value

def pct(v, d=1): return f"{v * 100:.{d}f}\\%"
def f(v, d=3): return f"{v:.{d}f}"

m("dbRowsRaw", f"{S['rows_raw']:,}"); m("dbRowsClean", f"{S['rows_clean']:,}"); m("dbDup", f"{S['duplicates_removed']:,}")
m("dbPrev", pct(S["prevalence"])); m("dbTrain", f"{S['train']:,}"); m("dbTest", f"{S['test']:,}")
m("dbRuleShare", pct(S["rule_share"])); m("dbRuleRate", pct(S["rule_diabetes_rate"])); m("dbRuleCapture", pct(S["rule_capture"]))

b = S["best"]
m("dbBestName", S["best_model"]); m("dbBestThr", f(S["best_threshold"], 2))
for k, key in [("Acc", "Accuracy"), ("Prec", "Precision"), ("Rec", "Recall"), ("Fone", "F1"), ("Auc", "ROC-AUC"), ("Prauc", "PR-AUC")]:
    m(f"dbBest{k}", f(b[key])); m(f"dbBest{k}Pct", pct(b[key]))
for tag, row in [("Lr", S["lr_test"]), ("Dt", S["dt_test"])]:
    for k, key in [("Acc", "Accuracy"), ("Prec", "Precision"), ("Rec", "Recall"), ("Fone", "F1"), ("Auc", "ROC-AUC"), ("Prauc", "PR-AUC")]:
        m(f"db{tag}{k}", f(row[key]))
m("dbTuneAp", f(S["tuning_cv_pr_auc"], 4)); m("dbTuneSec", f"{S['tuning_seconds'] / 60:.1f}")
mc = S["mcnemar"]
m("dbMcBest", f"{mc['only_best_correct']}"); m("dbMcLr", f"{mc['only_lr_correct']}"); m("dbMcChi", f(mc["chi2"], 1))
m("dbMcP", f"{mc['p']:.1e}".replace("e-0", "\\times10^{-").replace("e-", "\\times10^{-") + "}")
rf = S["rf_auc_by_trees"]; m("dbRfOne", f(rf["1"])); m("dbRfAll", f(rf["300"]))
m("dbGbFirst", f(S["gb_stage_auc_first_last"][0])); m("dbGbLast", f(S["gb_stage_auc_first_last"][1]))

bd = S["best_default"]
for k, key in [("Acc", "Accuracy"), ("Prec", "Precision"), ("Rec", "Recall"), ("Fone", "F1"), ("Auc", "ROC-AUC"), ("Prauc", "PR-AUC")]:
    m(f"dbBestDef{k}", f(bd[key]))
ens_sig = [r for r in S["significance"] if r["Model"] != "Decision Tree"]
m("dbSigMaxP", f"{max(r['p-value'] for r in ens_sig):.4f}")
m("dbSigMinGain", f"{min(r['Mean ΔF1 vs LR'] for r in ens_sig):.3f}")
m("dbSigMaxGain", f"{max(r['Mean ΔF1 vs LR'] for r in ens_sig):.3f}")
nice = lambda k: k.replace("_level", "").replace("_", " ").replace("HbA1c", "HbA1c").replace("blood glucose", "blood glucose")
shap = list(S["shap_mean_abs"].items())
m("dbShapTop", ", ".join(nice(k) for k, _ in shap[:5]))
m("dbShapFirst", nice(shap[0][0])); m("dbShapSecond", nice(shap[1][0]))
m("dbShapModel", S["shap_model"])
perm = list(S["perm_importance"].items())
m("dbPermFirst", nice(perm[0][0])); m("dbPermFirstVal", f(perm[0][1])); m("dbPermSecond", nice(perm[1][0])); m("dbPermSecondVal", f(perm[1][1]))
m("dbPermThird", nice(perm[2][0])); m("dbPermThirdVal", f(perm[2][1]))

# Tables
name_tex = lambda s: s.replace("&", "\\&")
def cv_table():
    rows = []
    for r in S["cv"]:
        hl = "\\rowcolor{lightorange} " if r["Model"] == S["cv"][0]["Model"] else ""
        rows.append(f"{hl}{name_tex(r['Model'])} & {r['Family']} & {r['CV f1']:.4f} $\\pm$ {r['CV F1 std']:.4f} & "
                    f"{r['CV roc_auc']:.4f} & {r['CV pr_auc']:.4f} & {r['CV precision']:.3f} & {r['CV recall']:.3f} & {r['CV time (s)']:.0f} \\\\")
    return "\n".join(rows)
def test_table():
    rows = []
    for r in S["test_default"]:
        hl = "\\rowcolor{lightorange} " if r["Model"] == S["test_default"][0]["Model"] else ""
        rows.append(f"{hl}{name_tex(r['Model'])} & {r['Accuracy']:.4f} & {r['Precision']:.3f} & {r['Recall']:.3f} & "
                    f"{r['F1']:.4f} & {r['ROC-AUC']:.4f} & {r['PR-AUC']:.4f} & {r['Fit time (s)']:.1f} \\\\")
    return "\n".join(rows)
def thr_table():
    rows = []
    for r in S["threshold"]:
        hl = "\\rowcolor{lightorange} " if r["Model"] == S["best_model"] else ""
        rows.append(f"{hl}{name_tex(r['Model'])} & {r['Threshold']:.2f} & {r['Accuracy']:.4f} & {r['Precision']:.3f} & "
                    f"{r['Recall']:.3f} & {r['F1']:.4f} & {r['ROC-AUC']:.4f} \\\\")
    return "\n".join(rows)
def sig_table():
    rows = []
    for r in S["significance"]:
        p = r["p-value"]; ps = f"{p:.4f}" if p >= 1e-4 else f"{p:.1e}"
        rows.append(f"{name_tex(r['Model'])} & {r['Mean ΔF1 vs LR']:+.4f} & {ps} \\\\")
    return "\n".join(rows)
def tuned_table():
    return "\n".join(f"\\texttt{{{k.replace('_', chr(92) + '_')}}} & {v} \\\\" for k, v in S["tuned_params"].items())

out = ["% Auto-generated by build_numbers.py — do not edit by hand"]
out += [f"\\newcommand{{\\{k}}}{{{v}}}" for k, v in macros.items()]
for name, body in [("dbCvRows", cv_table()), ("dbTestRows", test_table()), ("dbThrRows", thr_table()),
                   ("dbSigRows", sig_table()), ("dbTunedRows", tuned_table())]:
    out.append(f"\\newcommand{{\\{name}}}{{%\n{body}\n}}")
(HERE / "numbers.tex").write_text("\n".join(out) + "\n")
print(f"wrote numbers.tex with {len(macros)} macros")
